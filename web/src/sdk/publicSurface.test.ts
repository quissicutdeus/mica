/** One way the live surface would break something already written against the baseline. */
interface Break {
  /** `'@gphone/sdk'` for an export, the component name for a prop. */
  where: string;
  what: string;
  kind:
    | 'export removed'
    | 'prop removed'
    | 'prop lost its default'
    | 'shape could not be read'
    | 'vocabulary member removed';
}

/**
 * A prop list keyed by the name a caller writes, valued by whether the component supplies
 * a default for it. Splitting the two apart is what lets the differ tell a prop that
 * vanished from one that merely stopped being optional — and keeps a prop that *gained* a
 * default from reading as a removal, which is a widening and breaks nobody.
 */
const defaults = (props: string[]): Map<string, boolean> =>
  new Map(props.map((p) => [p.replace(/\?$/, ''), p.endsWith('?')]));

/**
 * Every breaking difference between the live surface and the frozen one.
 *
 * Pure, so the probes at the bottom can drive it with input this repo does not have.
 */
interface Surface {
  exports: Record<string, string[]>;
  props: Record<string, string[]>;
  /** Optional so the probes below can name only the axis they are exercising. */
  vocabularies?: Record<string, string[]>;
}

const breakingChanges = (live: Surface, baseline: Surface): Break[] => {
  const breaks: Break[] = [];

  for (const [entry, names] of Object.entries(baseline.exports)) {
    const now = new Set(live.exports[entry] ?? []);
    for (const name of names) {
      if (!now.has(name)) breaks.push({ where: entry, what: name, kind: 'export removed' });
    }
  }

  for (const [component, props] of Object.entries(baseline.props)) {
    if (!(component in live.props)) {
      // A component that is gone entirely is already reported as a removed export; listing
      // each of its props again would bury that one line under twenty. But one that is
      // *still exported* and has no parsed shape is a different animal: the parse went
      // blind, and skipping it would leave its props unchecked without a word. That is the
      // fail-open shape AGENTS.md names, so it is reported instead.
      const stillExported = Object.values(live.exports).some((names) => names.includes(component));
      if (stillExported) {
        breaks.push({ where: component, what: 'its props', kind: 'shape could not be read' });
      }
      continue;
    }
    const now = defaults(live.props[component]);
    for (const [name, hadDefault] of defaults(props)) {
      if (!now.has(name)) {
        breaks.push({
          where: component,
          what: hadDefault ? `${name}?` : name,
          kind: 'prop removed'
        });
      } else if (hadDefault && !now.get(name)) {
        // The other direction — a prop that gains a default — widens what callers may
        // omit and breaks nobody, so it is deliberately not reported.
        breaks.push({ where: component, what: name, kind: 'prop lost its default' });
      }
    }
  }

  for (const [name, members] of Object.entries(baseline.vocabularies ?? {})) {
    // A vocabulary that vanished entirely is already an `export removed` line above.
    const now = new Set(live.vocabularies?.[name] ?? []);
    if (now.size === 0) continue;
    for (const member of members) {
      if (!now.has(member)) {
        breaks.push({ where: name, what: member, kind: 'vocabulary member removed' });
      }
    }
  }

  return breaks;
};

const describeBreak = (b: Break): string => `${b.where}: ${b.what} (${b.kind})`;

