/**
 * The SDK's public surface, frozen — so a change that breaks a published add-on cannot
 * ship without somebody saying so (MICA-125).
 *
 * ## The incident this exists for
 *
 * On 2026-08-28 `sdk/ui/ReactionBar.svelte` went from `counts` / `mine` / `onreact` /
 * `onunreact` to `summary` / `ontoggle`. Every in-tree call site was updated in the same
 * commit, so `typecheck`, `test:unit` and `test:e2e` were all green — and every published
 * `core: false` add-on that drew a reaction row was broken, silently, with the CHANGELOG
 * saying "Action required: None". An audit found it. No check could have.
 *
 * The important detail is that **`ReactionBar` was exported before and after**. A gate
 * that diffs export *names* would have watched that break go past — and so would it have
 * for the other two silent breaks of the same fortnight: `Screen`'s layout contract, and
 * `'sound'` disappearing from `ALL_PERMISSIONS` while the array kept its name. Of the
 * eleven breaking SDK changes in this project's life, a name-level snapshot would have
 * caught six, and none of the three most recent.
 *
 * So this file captures four things, and only the first is a list of names:
 *
 *   1. the exported names of each entry point an app can actually name,
 *   2. the **props** of every exported Svelte component,
 *   3. the **members** of every exported string vocabulary (`ALL_PERMISSIONS`), and
 *   4. **parity between `index.ts` and `addon.ts`** — the two files `@gphone/sdk`
 *      resolves to depending on who is building. See that section for why.
 *
 * ## What counts as breaking
 *
 * Five things fail this gate, and every one of them breaks code that already exists:
 *
 *   - an export in the baseline that is gone,
 *   - a prop in the baseline that is gone (a **rename** shows up as exactly this),
 *   - a prop that had a default and no longer does — a call site that omitted it now
 *     gets `undefined` where it used to get a value,
 *   - a member dropped from an exported vocabulary, and
 *   - a name that crosses one of the two `@gphone/sdk` barrels and not the other,
 *     without being declared as a deliberate difference.
 *
 * **Additions pass, deliberately.** A new icon, a new hook, a new optional prop, a new
 * permission breaks nobody, and `icons.ts` / `kit/index.ts` / `host/index.ts` are
 * generated by `scripts/generate-barrels.js` — adding a file to a directory grows the
 * surface on its own. A gate that demanded a version bump for a new icon would be routed
 * around inside a week, and a gate somebody has switched off is a silent failure with
 * extra steps. The consequence is worth stating: a surface can still *widen* by `git add`
 * with nobody deciding it should be public. That is a review question, not a build one.
 *
 * ## What this cannot see, said plainly
 *
 * - **A layout or behavioural contract.** The two `Screen` changes of 2026-08 gave the
 *   content box a definite height and then took ownership of the app viewport. Neither
 *   touched a single export or prop, and both broke any add-on whose child used `h-full`
 *   or a bare `flex-1` — legal the day before. `utilityClasses.test.ts` enforces the new
 *   rule against **in-tree apps only**. No export list, no prop signature and no `.d.ts`
 *   would show this, and nothing in this file tries to. It is the largest gap and it is
 *   deliberate.
 * - **A prop's type.** `size: string` narrowing to `size: 'sm' | 'lg'`, or `number`
 *   becoming `string`, is a break this file is blind to. It reads names and defaults.
 * - **A prop that is newly required.** Optionality is read from whether the destructure
 *   supplies a default, because the three annotation shapes in this tree
 *   (`interface Props`, `$props<{...}>()`, an inline `: { class?: string }`) and
 *   `Button`'s `interface Props extends HTMLButtonAttributes` cannot all be read the same
 *   way. Optional-with-no-default is normal here (`Screen`'s `onback`), so treating a new
 *   no-default prop as required would fire on changes that break nothing. Rather than cry
 *   wolf, this gate does not see it.
 * - **Type-only exports, except across the two barrels.** The name list in
 *   `BASELINE_EXPORTS` is read from the real modules at runtime, which is what makes
 *   `export *` through three generated barrels work without reimplementing the resolver —
 *   but `export type { Host }` has no runtime footprint, so dropping or renaming an
 *   exported *type* passes that arm. The parity block reads both barrels statically and
 *   does see types, so a type that stops crossing into an add-on's bundle is caught even
 *   though a type deleted from both is not.
 * - **Behaviour behind a name that did not move.** A prop keeping its name and meaning
 *   something else is invisible here and always will be.
 * - **`@gphone/sdk/testing`.** Test-only, aliased for this repo's own suites and not for
 *   an add-on's bundle (`vite.addon.config.ts` does not map it), so it is not a contract
 *   with anybody outside this tree.
 *
 * A last one that is not a blind spot but is worth knowing: `defineApp` types
 * `manifest.permissions` as `AppPermission[]` and never validates it against
 * `ALL_PERMISSIONS` at runtime. That is why arm 3 exists — a shrinking vocabulary has no
 * runtime signal of its own.
 *
 * Nothing here reads git — no parent commit, no merge base, no `git status`. Those answer
 * differently on a shallow CI clone, on a clean tree and mid-rebase, so a gate built on
 * one is a gate that only runs in one place. The inputs are the live modules, the two
 * barrel sources and the frozen lists below, so a local run and a CI run see the same
 * thing or both fail.
 */

/**
 * What `BASELINE_EXPORTS` and `BASELINE_PROPS` below were captured at.
 *
 * The pin itself — `SDK_CONTRACT_VERSION` — is imported from `sdk/version.ts` above, and
 * this literal is what it is checked against. **They must stay equal**, which is the whole
 * mechanism: landing a break means bumping the exported constant *and* re-freezing the
 * baselines here in the same commit, so the break is a deliberate, reviewable line in a
 * diff rather than a silence.
 *
 * This half stays a literal in this file on purpose. It is not a second copy of the pin —
 * it is the record of what the lists underneath it were captured at, and importing it too
 * would make `has a baseline frozen at the version it is pinned to` compare a value with
 * itself and pass forever. One number is authored where an add-on can read it; the other
 * sits next to the frozen data it describes, which is what lets them disagree at all.
 *
 * The pin used to live here as well, and MICA-173 moved it: this file said outright that
 * "an add-on author cannot import this number", which made the one number in the tree with
 * real compatibility meaning unreadable by the only people who needed it. `sdk/version.ts`
 * is where it went, for the reasons written there — briefly, `MICA_VERSION` is a CalVer
 * build stamp that moves on every push, and `package.json`'s `1.0.0` is read by no code.
 */
const BASELINE_VERSION = '1';

const SDK_DIR = __dirname;

/**
 * The entry points an app can name, and what each resolves to.
 *
 * `@gphone/sdk` appears twice on purpose. In-process it is `index.ts`; inside a
 * `core: false` add-on's own bundle `vite.addon.config.ts` redirects it to `addon.ts`,
 * which is a **different and smaller** list. The add-on one is the contract that matters
 * for MICA-125 — it is what a published add-on actually compiled against — and the two
 * have already drifted once (`fade`/`fly` were on `index.ts` and missing from `addon.ts`
 * until Notes reached for them).
 */
const ENTRY_POINTS: Record<string, Record<string, unknown>> = {
  '@gphone/sdk': sdkIndex,
  '@gphone/sdk (add-on bundle)': sdkAddon,
  '@gphone/sdk/app': sdkApp,
  '@gphone/sdk/core': sdkCore
};

/** Barrels that re-export a `.svelte` default, and so decide which components are public. */
const COMPONENT_BARRELS = ['components.ts', 'icons.ts', 'core.ts'];

// ---------------------------------------------------------------------------
// Reading the live surface
// ---------------------------------------------------------------------------

/** The runtime export names of one entry point, sorted. */
const exportNames = (module: Record<string, unknown>): string[] =>
  Object.keys(module)
    .filter((name) => name !== 'default' && name !== '__esModule')
    .sort();

/**
 * Every exported component, mapped to the `.svelte` file behind it.
 *
 * Read from the barrel source rather than from the runtime module, because a compiled
 * Svelte 5 component is a plain function and is indistinguishable at runtime from the
 * dozens of exported hooks beside it. The barrels state the mapping outright, and
 * `every exported component is reachable from an entry point` below cross-checks the two
 * lists against each other so this parse cannot quietly go blind.
 */
const publicComponents = (): Record<string, string> => {
  const found: Record<string, string> = {};
  for (const barrel of COMPONENT_BARRELS) {
    const source = readFileSync(join(SDK_DIR, barrel), 'utf8');
    for (const m of source.matchAll(
      /^\s*export\s+\{\s*default\s+as\s+(\w+)\s*\}\s*from\s+'([^']+\.svelte)'/gm
    )) {
      found[m[1]] = join(SDK_DIR, m[2]);
    }
  }
  return found;
};

/** The contents of every `<script>` block in a Svelte file, run together. */
const scriptOf = (source: string): string =>
  [...source.matchAll(/<script[^>]*>([\s\S]*?)<\/script>/g)].map((m) => m[1]).join('\n');

/**
 * TypeScript with its comments removed, strings left intact.
 *
 * Needed before any brace matching: a JSDoc block above the destructure is full of braces
 * and a `//` in a default string value would otherwise eat the rest of the line.
 */
const stripComments = (source: string): string => {
  let out = '';
  let mode: 'code' | 'line' | 'block' | "'" | '"' | '`' = 'code';
  for (let i = 0; i < source.length; i++) {
    const c = source[i];
    const two = source.slice(i, i + 2);
    if (mode === 'code') {
      if (two === '//') {
        mode = 'line';
        i++;
        continue;
      }
      if (two === '/*') {
        mode = 'block';
        i++;
        continue;
      }
      if (c === "'" || c === '"' || c === '`') mode = c;
      out += c;
      continue;
    }
    if (mode === 'line') {
      if (c === '\n') {
        mode = 'code';
        out += '\n';
      }
      continue;
    }
    if (mode === 'block') {
      if (two === '*/') {
        mode = 'code';
        i++;
      }
      continue;
    }
    out += c;
    if (c === '\\') {
      out += source[i + 1] ?? '';
      i++;
      continue;
    }
    if (c === mode) mode = 'code';
  }
  return out;
};

/**
 * The text inside the `let { ... } = $props()` destructure, or `null` if there is none.
 *
 * Found by walking left from `$props` and balancing braces, which is what makes it work
 * for both shapes in this tree — `let { a }: Props = $props()` and
 * `let { a } = $props<{ a: string }>()` — without caring which one it is looking at.
 */
const propsDestructure = (script: string): string | null => {
  const call = /=\s*\$props\s*[<(]/.exec(script);
  if (!call) return null;

  let close = call.index - 1;
  while (close >= 0 && /\s/.test(script[close])) close--;
  // `let { a }: Props = $props()` puts the annotation between the brace and the `=`.
  if (script[close] !== '}') {
    const colon = script.lastIndexOf('}', close);
    if (colon === -1) return null;
    close = colon;
  }
  if (script[close] !== '}') return null;

  let depth = 0;
  for (let i = close; i >= 0; i--) {
    const c = script[i];
    if (c === '}') depth++;
    else if (c === '{') {
      depth--;
      if (depth === 0) return script.slice(i + 1, close);
    }
  }
  return null;
};

/** Split on commas that are not inside brackets or a string. */
const splitTopLevel = (body: string): string[] => {
  const parts: string[] = [];
  let depth = 0;
  let current = '';
  let quote: string | null = null;

  for (let i = 0; i < body.length; i++) {
    const c = body[i];
    if (quote) {
      current += c;
      if (c === '\\') {
        current += body[i + 1] ?? '';
        i++;
      } else if (c === quote) quote = null;
      continue;
    }
    if (c === "'" || c === '"' || c === '`') {
      quote = c;
      current += c;
      continue;
    }
    if ('([{<'.includes(c) && c !== '<') depth++;
    else if (')]}'.includes(c)) depth--;
    else if (c === ',' && depth === 0) {
      parts.push(current);
      current = '';
      continue;
    }
    current += c;
  }
  parts.push(current);
  return parts.map((p) => p.trim()).filter((p) => p.length > 0);
};

/**
 * One destructured prop, encoded for the baseline: `name` when the component requires the
 * caller to supply it, `name?` when the destructure supplies a default, and `...` for a
 * rest element (dropping which stops arbitrary attributes being forwarded).
 *
 * The name is the **public** one — `class: className = ''` is `class?`, because `class` is
 * what a caller writes and `className` is a local variable nobody outside can see.
 */
const encodeProp = (entry: string): string => {
  if (entry.startsWith('...')) return '...';

  let depth = 0;
  let quote: string | null = null;
  let split = -1;
  for (let i = 0; i < entry.length; i++) {
    const c = entry[i];
    if (quote) {
      if (c === '\\') i++;
      else if (c === quote) quote = null;
      continue;
    }
    if (c === "'" || c === '"' || c === '`') {
      quote = c;
      continue;
    }
    if ('([{'.includes(c)) depth++;
    else if (')]}'.includes(c)) depth--;
    else if (
      c === '=' &&
      depth === 0 &&
      entry[i + 1] !== '=' &&
      entry[i + 1] !== '>' &&
      !['=', '!', '<', '>'].includes(entry[i - 1])
    ) {
      split = i;
      break;
    }
  }

  const head = (split === -1 ? entry : entry.slice(0, split)).trim();
  const name = head
    .split(':')[0]
    .trim()
    .replace(/^['"]|['"]$/g, '');
  return split === -1 ? name : `${name}?`;
};

/**
 * A component's props, sorted, or `null` when the file declares `$props` and this parser
 * could not read it. `null` is a failure, not an empty answer — see the guard below.
 */
const propsOf = (file: string): string[] | null => {
  const script = stripComments(scriptOf(readFileSync(file, 'utf8')));
  if (!/\$props\s*[<(]/.test(script)) return [];

  const body = propsDestructure(script);
  if (body === null) return null;
  return splitTopLevel(body).map(encodeProp).sort();
};

/** Every exported component's props, keyed by the name a caller imports. */
const liveProps = (): Record<string, string[] | null> => {
  const out: Record<string, string[] | null> = {};
  for (const [name, file] of Object.entries(publicComponents())) out[name] = propsOf(file);
  return out;
};

const liveExports = (): Record<string, string[]> =>
  Object.fromEntries(Object.entries(ENTRY_POINTS).map(([id, mod]) => [id, exportNames(mod)]));

