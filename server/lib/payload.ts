/**
 * What is left of the hand-written NUI parsers.
 *
 * This file was where a service went to read a payload: `fields` to make one indexable,
 * `optionalString` and `requirePositiveInt` to pull a value out of it, one call per field per
 * handler. `shared/schema.ts` does that from a declaration now, so what remains is the part a
 * schema genuinely cannot express.
 *
 * - `requirePositiveInt` still parses an id a **handler** produced rather than one a payload
 *   carried — a value read off a row, or one an ownership check is about to discard. Its
 *   reasoning about `Number([7])` moved into the DSL's own tests, where the ninety-seven
 *   handlers that used to repeat it now inherit it.
 * - `conversationIdFrom` answers "which of two spellings arrived", which is a rule about a
 *   payload as a whole rather than about a field.
 * - `flagUnlessFalse` is a default, not a check: absent means true.
 * - `pageBounds` **clamps** rather than refuses, which is the one place this file deliberately
 *   disagrees with the schema's instinct — see its own note.
 * - `fields` survives for the two raw `onNet` handlers that never pass through
 *   `ServiceEndpoint` and so have no contract in front of them.
 *
 * Every id in a `gphone:server:*` payload is still attacker-controlled (AGENTS.md §2.9); what
 * changed is where that is written down.
 */
import { PlayerFacingError } from './errors';

/**
 * The correlation id `fetchNui` sent with the request, echoed back on the reply.
 *
 * Opaque to the server — it is generated by the web and only ever passed through — so
 * it is typed as what it can be rather than as `any`.
 */
export type CallbackId = string | number;

/**
 * Coerce to a positive integer or throw. Rejects '', null, NaN, 0, negatives and
 * fractions — and rejects non-scalars up front, because `Number([7])` is `7`, so a
 * bare `Number()` coercion would quietly accept `{ id: [7] }` from a client.
 */
export function requirePositiveInt(raw: unknown, what: string): number {
  if (typeof raw !== 'number' && typeof raw !== 'string') {
    throw new PlayerFacingError(`A valid ${what} is required.`);
  }
  const value = Number(raw);
  if (!Number.isInteger(value) || value <= 0) {
    throw new PlayerFacingError(`A valid ${what} is required.`);
  }
  return value;
}

/**
 * Pull a conversation id out of a payload. Accepts `{ conversation_id }`, `{ id }`,
 * or a bare id — the UI is not consistent about which it sends.
 */
export function conversationIdFrom(data: unknown): number {
  const raw = isRecord(data) ? (data.conversation_id ?? data.id) : data;
  return requirePositiveInt(raw, 'conversation_id');
}

/**
 * A NUI payload as something with readable fields.
 *
 * For a raw `onNet` handler, which receives `unknown` and has no contract in front of it —
 * `contacts:share` is the one that still reads a whole object this way. A payload that is not
 * an object reads as empty rather than throwing, because a missing field and a malformed
 * envelope deserve the same answer.
 */
function isRecord(value: unknown): value is Record<string, unknown> {
  return !!value && typeof value === 'object' && !Array.isArray(value);
}

export function fields(data: unknown): Record<string, unknown> {
  return isRecord(data) ? data : {};
}

/** `true` unless the client explicitly said `false` — the shape these flags default to. */
export function flagUnlessFalse(raw: unknown): boolean {
  return raw !== false;
}

/**
 * The page a custom action was asked for, clamped to what the service declared.
 *
 * `defineService` clamps the generic `get` inside `ServiceEndpoint`; a custom action does its own
 * paging and so has to clamp its own. This was written once inside `Blabber.ts` for `profile` and
 * `following`, and the accounts service's follower lists made it the third and fourth call site —
 * so it moves here rather than being copied again. It takes the resolved `paging` instead of
 * hardcoding the numbers, which is what stops a change to a declaration from silently missing that
 * service's custom actions.
 *
 * An over-large `limit` is clamped rather than refused (§10): the request is legitimate, only the
 * number is not. The cursor is a bare row id and never a column — the sort order comes from the
 * query, so a payload offering one is ignored rather than honored.
 *
 * `ServiceEndpoint` keeps its own private pair on the generic path deliberately, because its cursor
 * error names the service it was asked of; the numbers still come from one declaration either way.
 */
export function pageBounds(
  data: unknown,
  paging: { pageSize: number; maxPageSize: number }
): { limit: number; cursor: number | null } {
  const body = fields(data);
  const rawLimit = body.limit;
  return {
    limit:
      typeof rawLimit === 'number' && Number.isInteger(rawLimit) && rawLimit > 0
        ? Math.min(rawLimit, paging.maxPageSize)
        : paging.pageSize,
    cursor:
      body.cursor === undefined || body.cursor === null
        ? null
        : requirePositiveInt(body.cursor, 'cursor')
  };
}
