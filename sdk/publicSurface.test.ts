/**
 * The SDK's public surface, frozen — so a change that breaks a published add-on cannot
 * ship without somebody saying so (MICA-125).
 *
 * ## The incident this exists for
 *
 * On 2026-08-28 `sdk/ui/ReactionBar.svelte` went from `counts` / `mine` / `onreact` /
 * `onunreact` to `summary` / `ontoggle`. Every in-tree call site was updated in the same
 * commit, so `typecheck`, `test:unit` and `test:e2e` were all green — and every published
 * `core: false` add-on that drew a reaction row was broken, silently, with the CHANGELOG
 * saying "Action required: None". An audit found it. No check could have.
 *
 * The important detail is that **`ReactionBar` was exported before and after**. A gate
 * that diffs export *names* would have watched that break go past — and so would it have
 * for the other two silent breaks of the same fortnight: `Screen`'s layout contract, and
 * `'sound'` disappearing from `ALL_PERMISSIONS` while the array kept its name. Of the
 * eleven breaking SDK changes in this project's life, a name-level snapshot would have
 * caught six, and none of the three most recent.
 *
 * So this file captures six things, and only the first two are lists of names:
 *
 *   1. the exported **values** of each entry point an app can actually call, read by
 *      importing the real modules,
 *   2. the exported **types** of each entry point, which compile to nothing and so are
 *      invisible to that import — read from the typechecker instead (MICA-182),
 *   3. the **props** of every exported Svelte component,
 *   4. the **members** of every exported string vocabulary (`ALL_PERMISSIONS`),
 *   5. the **members of the object every exported hook returns** (MICA-188), read off the
 *      hook's call signature through the same typechecker, and
 *   6. **parity between `index.ts` and `addon.ts`** — the two files `@mica/sdk`
 *      resolves to depending on who is building. See that section for why.
 *
 * The first two are deliberately two arms and not one, because they answer different
 * questions. `import * as sdk from './index'` proves a name **exists at runtime** — a
 * barrel that throws on load, or an `export *` that resolves to nothing, fails there and
 * nowhere else. `checker.getExportsOfModule` proves a name **resolves for the typechecker**
 * — which is the only thing an `export type` has ever done. Neither subsumes the other, and
 * the gate asserts the two agree on the value half rather than assuming it.
 *
 * ## What counts as breaking
 *
 * Six things fail this gate, and every one of them breaks code that already exists:
 *
 *   - an export in the baseline that is gone,
 *   - a type-only export in the baseline that is gone (a **rename** is exactly this: the
 *     old name removed, the new one an addition that passes),
 *   - a prop in the baseline that is gone (a **rename** shows up as exactly this),
 *   - a prop that had a default and no longer does — a call site that omitted it now
 *     gets `undefined` where it used to get a value,
 *   - a member dropped from an exported vocabulary,
 *   - a member dropped from what an exported hook returns — `useTheme()` going from
 *     `{ theme, setTheme }` to `{ theme }` moves no name, no type and no prop, and breaks
 *     every add-on that destructured it (MICA-127), and
 *   - a name that crosses one of the two `@mica/sdk` barrels and not the other,
 *     without being declared as a deliberate difference.
 *
 * **Additions pass, deliberately.** A new icon, a new hook, a new optional prop, a new
 * permission breaks nobody, and `icons.ts` / `kit/index.ts` / `host/index.ts` are
 * generated by `scripts/generate-barrels.js` — adding a file to a directory grows the
 * surface on its own. A gate that demanded a version bump for a new icon would be routed
 * around inside a week, and a gate somebody has switched off is a silent failure with
 * extra steps. The consequence is worth stating: a surface can still *widen* by `git add`
 * with nobody deciding it should be public. That is a review question, not a build one.
 *
 * ## What this cannot see, said plainly
 *
 * - **A layout or behavioural contract.** The two `Screen` changes of 2026-08 gave the
 *   content box a definite height and then took ownership of the app viewport. Neither
 *   touched a single export or prop, and both broke any add-on whose child used `h-full`
 *   or a bare `flex-1` — legal the day before. `utilityClasses.test.ts` enforces the new
 *   rule against **in-tree apps only**. No export list, no prop signature and no `.d.ts`
 *   would show this, and nothing in this file tries to. It is the largest gap and it is
 *   deliberate.
 * - **A prop's type.** `size: string` narrowing to `size: 'sm' | 'lg'`, or `number`
 *   becoming `string`, is a break this file is blind to. It reads names and defaults.
 * - **A prop that is newly required.** Optionality is read from whether the destructure
 *   supplies a default, because the three annotation shapes in this tree
 *   (`interface Props`, `$props<{...}>()`, an inline `: { class?: string }`) and
 *   `Button`'s `interface Props extends HTMLButtonAttributes` cannot all be read the same
 *   way. Optional-with-no-default is normal here (`Screen`'s `onback`), so treating a new
 *   no-default prop as required would fire on changes that break nothing. Rather than cry
 *   wolf, this gate does not see it.
 * - **A type's *shape*.** MICA-182 closed the hole where an exported type could be
 *   renamed or deleted outright with every gate green, but only at the level of names.
 *   `interface AppProps { id: string }` becoming `{ appId: string }` keeps the name
 *   `AppProps` on the entry point and passes here, exactly as a renamed prop on a
 *   still-exported component would have before `BASELINE_PROPS` existed. That is the same
 *   gap `BASELINE_PROPS` was written to close for components, one level up, and nothing
 *   here closes it for types.
 * - **Behaviour behind a name that did not move.** A prop keeping its name and meaning
 *   something else is invisible here and always will be.
 * - **`@mica/sdk/testing`.** Test-only, aliased for this repo's own suites and not for
 *   an add-on's bundle (`vite.addon.config.ts` does not map it), so it is not a contract
 *   with anybody outside this tree.
 *
 * A last one that is not a blind spot but is worth knowing: `defineApp` types
 * `manifest.permissions` as `AppPermission[]` and never validates it against
 * `ALL_PERMISSIONS` at runtime. That is why arm 4 exists — a shrinking vocabulary has no
 * runtime signal of its own.
 *
 * Nothing here reads git — no parent commit, no merge base, no `git status`. Those answer
 * differently on a shallow CI clone, on a clean tree and mid-rebase, so a gate built on
 * one is a gate that only runs in one place. The inputs are the live modules, the two
 * barrel sources and the frozen lists below, so a local run and a CI run see the same
 * thing or both fail.
 */

/**
 * What `BASELINE_EXPORTS` and `BASELINE_PROPS` below were captured at.
 *
 * The pin itself — `SDK_CONTRACT_VERSION` — is imported from `sdk/version.ts` above, and
 * this literal is what it is checked against. **They must stay equal**, which is the whole
 * mechanism: landing a break means bumping the exported constant *and* re-freezing the
 * baselines here in the same commit, so the break is a deliberate, reviewable line in a
 * diff rather than a silence.
 *
 * This half stays a literal in this file on purpose. It is not a second copy of the pin —
 * it is the record of what the lists underneath it were captured at, and importing it too
 * would make `has a baseline frozen at the version it is pinned to` compare a value with
 * itself and pass forever. One number is authored where an add-on can read it; the other
 * sits next to the frozen data it describes, which is what lets them disagree at all.
 *
 * The pin used to live here as well, and MICA-173 moved it: this file said outright that
 * "an add-on author cannot import this number", which made the one number in the tree with
 * real compatibility meaning unreadable by the only people who needed it. `sdk/version.ts`
 * is where it went, for the reasons written there — briefly, `MICA_VERSION` is a CalVer
 * build stamp that moves on every push, and `package.json`'s `1.0.0` is read by no code.
 */
const BASELINE_VERSION = '1';

const SDK_DIR = __dirname;

/**
 * The entry points an app can name, and what each resolves to.
 *
 * `@mica/sdk` appears twice on purpose. In-process it is `index.ts`; inside a
 * `core: false` add-on's own bundle `vite.addon.config.ts` redirects it to `addon.ts`,
 * which is a **different and smaller** list. The add-on one is the contract that matters
 * for MICA-125 — it is what a published add-on actually compiled against — and the two
 * have already drifted once (`fade`/`fly` were on `index.ts` and missing from `addon.ts`
 * until Notes reached for them).
 */
const ENTRY_POINTS: Record<string, Record<string, unknown>> = {
  '@mica/sdk': sdkIndex,
  '@mica/sdk (add-on bundle)': sdkAddon,
  '@mica/sdk/app': sdkApp,
  '@mica/sdk/core': sdkCore
};

/**
 * The same four entry points as files on disk, for the arm that asks the compiler rather
 * than the module loader. Kept beside `ENTRY_POINTS` rather than folded into it because the
 * two are read by different machinery; `asked the typechecker about every entry point`
 * below asserts they name the same four, so one cannot quietly lose an entry the other has.
 */
const ENTRY_FILES: Record<string, string> = {
  '@mica/sdk': 'index.ts',
  '@mica/sdk (add-on bundle)': 'addon.ts',
  '@mica/sdk/app': 'app.ts',
  '@mica/sdk/core': 'core.ts'
};

/** Barrels that re-export a `.svelte` default, and so decide which components are public. */
const COMPONENT_BARRELS = ['components.ts', 'icons.ts', 'core.ts'];

