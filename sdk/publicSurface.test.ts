/** One way the live surface would break something already written against the baseline. */
interface Break {
  /**
   * `'@mica/sdk'` for an export or a type, the component name for a prop, the hook name
   * for a return member.
   */
  where: string;
  what: string;
  kind:
    | 'export removed'
    | 'type export removed'
    | 'prop removed'
    | 'prop lost its default'
    | 'shape could not be read'
    | 'vocabulary member removed'
    | 'hook return member removed';
}

/**
 * A prop list keyed by the name a caller writes, valued by whether the component supplies
 * a default for it. Splitting the two apart is what lets the differ tell a prop that
 * vanished from one that merely stopped being optional — and keeps a prop that *gained* a
 * default from reading as a removal, which is a widening and breaks nobody.
 */
const defaults = (props: string[]): Map<string, boolean> =>
  new Map(props.map((p) => [p.replace(/\?$/, ''), p.endsWith('?')]));

/**
 * Every breaking difference between the live surface and the frozen one.
 *
 * Pure, so the probes at the bottom can drive it with input this repo does not have.
 */
interface Surface {
  exports: Record<string, string[]>;
  props: Record<string, string[]>;
  /** Optional so the probes below can name only the axis they are exercising. */
  vocabularies?: Record<string, string[]>;
  /** Type-only exports, keyed by entry point. Optional on the same terms. */
  types?: Record<string, string[]>;
  /** What each exported hook returns, keyed by hook name. Optional on the same terms. */
  hooks?: Record<string, string[]>;
}

const breakingChanges = (live: Surface, baseline: Surface): Break[] => {
  const breaks: Break[] = [];

  for (const [entry, names] of Object.entries(baseline.exports)) {
    const now = new Set(live.exports[entry] ?? []);
    for (const name of names) {
      if (!now.has(name)) breaks.push({ where: entry, what: name, kind: 'export removed' });
    }
  }

  for (const [entry, names] of Object.entries(baseline.types ?? {})) {
    // No empty-means-skip escape here, unlike the vocabulary arm below. A vocabulary that
    // vanished is already an `export removed` line; an entry point whose type list came back
    // empty is either a real wipe of every published type or an arm that stopped resolving,
    // and both of those must be loud.
    const now = new Set(live.types?.[entry] ?? []);
    for (const name of names) {
      if (!now.has(name)) breaks.push({ where: entry, what: name, kind: 'type export removed' });
    }
  }

  for (const [component, props] of Object.entries(baseline.props)) {
    if (!(component in live.props)) {
      // A component that is gone entirely is already reported as a removed export; listing
      // each of its props again would bury that one line under twenty. But one that is
      // *still exported* and has no parsed shape is a different animal: the parse went
      // blind, and skipping it would leave its props unchecked without a word. That is the
      // fail-open shape AGENTS.md names, so it is reported instead.
      const stillExported = Object.values(live.exports).some((names) => names.includes(component));
      if (stillExported) {
        breaks.push({ where: component, what: 'its props', kind: 'shape could not be read' });
      }
      continue;
    }
    const now = defaults(live.props[component]);
    for (const [name, hadDefault] of defaults(props)) {
      if (!now.has(name)) {
        breaks.push({
          where: component,
          what: hadDefault ? `${name}?` : name,
          kind: 'prop removed'
        });
      } else if (hadDefault && !now.get(name)) {
        // The other direction — a prop that gains a default — widens what callers may
        // omit and breaks nobody, so it is deliberately not reported.
        breaks.push({ where: component, what: name, kind: 'prop lost its default' });
      }
    }
  }

  for (const [name, members] of Object.entries(baseline.vocabularies ?? {})) {
    // A vocabulary that vanished entirely is already an `export removed` line above.
    const now = new Set(live.vocabularies?.[name] ?? []);
    if (now.size === 0) continue;
    for (const member of members) {
      if (!now.has(member)) {
        breaks.push({ where: name, what: member, kind: 'vocabulary member removed' });
      }
    }
  }

  // MICA-188. Every arm above this one reads the surface at the module boundary and
  // stops: a name is there or it is not, a prop is there or it is not. `useTheme()` going
  // from `{ theme, setTheme }` to `{ theme }` moves no name, no type and no prop — the
  // hook is still exported, still a function, still returns an object — and every add-on
  // that destructured `setTheme` gets `undefined` and calls it. MICA-127 was that,
  // exactly, and nothing in this file would have said a word.
  //
  // Removal-only, like every other arm: an added member breaks nobody, and this gate is on
  // record (see the header) that a gate demanding paperwork for a widening is a gate
  // somebody switches off. Two things it therefore does not see, said plainly: a member
  // that stays but changes type, and one that goes from required to optional — the second
  // is a real narrowing, and reporting it wants the `defaults()` treatment the prop arm
  // gets. The optionality is captured in the baseline so that is a differ change and not a
  // re-freeze when somebody wants it.
  for (const [hook, members] of Object.entries(baseline.hooks ?? {})) {
    if (!(hook in (live.hooks ?? {}))) {
      // Same shape as the props arm: a hook that is gone entirely is already an
      // `export removed` line, but one still exported whose return shape came back
      // unreadable is a parse that went blind, and skipping it is the fail-open AGENTS.md
      // names. `returnMembers` returns `null` for a hook with nothing to freeze, so this
      // fires when a hook stops returning an object at all — which is itself a break.
      const stillExported = Object.values(live.exports).some((names) => names.includes(hook));
      if (stillExported) {
        breaks.push({ where: hook, what: 'what it returns', kind: 'shape could not be read' });
      }
      continue;
    }
    const now = new Set((live.hooks?.[hook] ?? []).map((m) => m.replace(/\?$/, '')));
    for (const member of members) {
      const name = member.replace(/\?$/, '');
      if (!now.has(name)) {
        breaks.push({ where: hook, what: member, kind: 'hook return member removed' });
      }
    }
  }

  return breaks;
};

const describeBreak = (b: Break): string => `${b.where}: ${b.what} (${b.kind})`;

/** A name on the live surface that no baseline records a decision about. */
interface Addition {
  where: string;
  what: string;
  kind: 'export' | 'type export' | 'vocabulary member';
}

/**
 * The other direction, and the one this file used to leave alone (MICA-180).
 *
 * `breakingChanges` above walks the *baseline* and asks whether each frozen name is still
 * there, so it can only ever see a removal. The docblock at the top of this file said so
 * outright — "a surface can still *widen* by `git add` with nobody deciding it should be
 * public. That is a review question, not a build one." That was a defensible call when the
 * SDK was a directory in this tree. It stopped being one when the SDK became a package an
 * outside author compiles against, because a widening is a **promise**: the moment an
 * add-on imports a name, removing it is a break, and under the old behaviour nobody ever
 * decided to make the promise.
 *
 * The mechanism is not hypothetical. `scripts/generate-barrels.js` globs `sdk/host/*.ts`
 * into `host/index.ts`, and `index.ts` re-exports that whole barrel — so writing a file in
 * that directory publishes every export in it, at `git add` time, with nothing reacting.
 * MICA-179 walked into it one ticket after MICA-176 deliberately put `host/seam/` a
 * directory down to avoid exactly that glob. When the people who know about the trap fall
 * into it, the trap is the problem.
 *
 * So this walks the *live* surface instead and reports names the baselines do not mention.
 * The cost is a line per genuine addition, which is the price of having decided.
 *
 * `derived` is the deliberate exemption, kept to names whose publication is not a per-name
 * decision at all: `sdk/icons.ts` is generated and its entire contract is that every icon
 * is republished, so demanding a baseline edit per icon would be ceremony for a choice
 * nobody makes. It exempts additions only — an icon that *disappears* is still a removal,
 * and `breakingChanges` still sees it.
 *
 * Props are deliberately out of scope, and so are hook return members. A new prop or a new
 * member is a widening too, but an optional one breaks nobody and the arms above already
 * treat it that way; this exists for names entering the surface, which is what the barrel
 * glob does silently.
 *
 * Pure, like its neighbour, so the probes at the bottom can drive it with input this repo
 * does not have.
 */
const undeclaredAdditions = (
  live: Surface,
  baseline: Surface,
  derived: ReadonlySet<string>
): Addition[] => {
  const additions: Addition[] = [];

  for (const [entry, names] of Object.entries(live.exports)) {
    const frozen = new Set(baseline.exports[entry] ?? []);
    for (const name of names) {
      if (!frozen.has(name) && !derived.has(name)) {
        additions.push({ where: entry, what: name, kind: 'export' });
      }
    }
  }

  for (const [entry, names] of Object.entries(live.types ?? {})) {
    const frozen = new Set(baseline.types?.[entry] ?? []);
    for (const name of names) {
      if (!frozen.has(name) && !derived.has(name)) {
        additions.push({ where: entry, what: name, kind: 'type export' });
      }
    }
  }

  for (const [vocabulary, members] of Object.entries(live.vocabularies ?? {})) {
    const frozen = new Set(baseline.vocabularies?.[vocabulary] ?? []);
    for (const member of members) {
      if (!frozen.has(member)) {
        additions.push({ where: vocabulary, what: member, kind: 'vocabulary member' });
      }
    }
  }

  return additions;
};

const describeAddition = (a: Addition): string => `${a.where}: ${a.what} (${a.kind} added)`;

