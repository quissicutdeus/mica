/**
 * Exported string vocabularies, and their members.
 *
 * The third silent break shape, and the one neither an export list nor a prop list sees:
 * on 2026-08-?? `'sound'` was dropped from `ALL_PERMISSIONS`. The export was still there
 * and still an array, so nothing moved — but `AppPermission` is *derived* from that array
 * and `defineApp` never validates `manifest.permissions` against it at runtime (it types
 * the field and defaults it to `[]`, nothing more). A published bundle declaring the
 * removed name therefore keeps loading with the declaration silently ignored, which is
 * worse than a refusal: the manifest still says the app asks for it.
 *
 * Any exported array of strings is treated as a vocabulary, so a second one added later is
 * covered without touching this code.
 */
const isStringArray = (value: unknown): value is readonly string[] =>
  Array.isArray(value) && value.length > 0 && value.every((v) => typeof v === 'string');

const vocabularies = (module: Record<string, unknown>): Record<string, string[]> => {
  const out: Record<string, string[]> = {};
  for (const [name, value] of Object.entries(module)) {
    if (isStringArray(value)) out[name] = [...value].sort();
  }
  return out;
};

