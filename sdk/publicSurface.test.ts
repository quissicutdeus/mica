/**
 * The second half of this gate, and the half that catches a defect this repo has today.
 *
 * `@mica/sdk` is **two files**. In-process it is `index.ts`; inside a `core: false`
 * add-on's own bundle `vite.addon.config.ts` rewrites the specifier to `addon.ts`. But
 * `tsconfig.app.json` maps it to `index.ts` for everybody, so an add-on that imports a
 * name present on `index.ts` and absent from `addon.ts` **typechecks clean and fails at
 * `vite build`** — and there is no alias for `@mica/sdk/core` in the add-on config at
 * all. `addon.ts`'s own docblock records that this has already bitten once: "Notes
 * reaching for `fade` is what found it."
 *
 * Nothing pinned the two together. `seam.test.ts` checks `addon.ts` for shell imports and
 * never compares its export list to `index.ts`'s.
 *
 * So: every difference between them must be **declared** below. The lists are not an
 * exemption mechanism — they are the record of which differences somebody chose, so that
 * a new one reddens the build instead of waiting for an add-on author to hit it.
 */

/** `export * from '...'` specifiers in a barrel. */
const starReexports = (file: string): string[] =>
  [...readFileSync(join(SDK_DIR, file), 'utf8').matchAll(/^export \* from '([^']+)'/gm)]
    .map((m) => m[1])
    .sort();

/**
 * Named re-exports in a barrel, types included and marked.
 *
 * Static, unlike `exportNames` above, and that is the point: `export type { Host }` has no
 * runtime footprint, so a type that crosses one barrel and not the other is invisible to
 * an import. Both barrels write their type re-exports as literal `export type { ... } from`
 * lines, which is exactly what this reads.
 */
const namedReexports = (file: string): string[] => {
  const source = readFileSync(join(SDK_DIR, file), 'utf8');
  const names: string[] = [];
  for (const m of source.matchAll(/^export\s+(type\s+)?\{([^}]*)\}\s*from\s*'[^']+'/gm)) {
    const blockIsType = Boolean(m[1]);
    for (const raw of m[2].split(',')) {
      const part = raw.trim();
      if (part.length === 0) continue;
      const isType = blockIsType || part.startsWith('type ');
      const bare = part.startsWith('type ') ? part.slice(5).trim() : part;
      const name = (bare.split(' as ').pop() ?? bare).trim();
      names.push(isType ? `type ${name}` : name);
    }
  }
  return [...new Set(names)].sort();
};

