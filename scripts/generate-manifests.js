import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const generateIndex = (dir, mode = 'import') => {
  const fullDir = path.resolve(__dirname, '..', dir);

  if (!fs.existsSync(fullDir)) {
    console.warn(`Directory not found: ${fullDir}`);
    return;
  }

  const files = fs
    .readdirSync(fullDir)
    .filter((file) => file.endsWith('.ts') && file !== 'index.ts');

  const lines = files
    .map((file) => {
      const name = file.replace('.ts', '');
      return mode === 'export' ? `export * from './${name}';` : `import './${name}';`;
    })
    .join('\n');

  const content = `// This file is auto-generated by scripts/generate-manifests.js
// Do not edit this file manually.
${lines}
`;

  fs.writeFileSync(path.join(fullDir, 'index.ts'), content);
  console.log(`Generated ${dir}/index.ts with ${files.length} ${mode}s.`);
};

console.log('Generating manifests...');
generateIndex('client/controllers', 'import');
generateIndex('server/controllers', 'import');
generateIndex('web/src/sdk/hooks', 'export');
console.log('Done.');
